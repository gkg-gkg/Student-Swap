// Generates the build's src/config/env.js from environment variables (Amplify Hosting -> Environment variables).
// Run automatically by `npm run build`. With no variables set it writes mock mode, so local builds just work.
//
//   STUDENTSWAP_USE_MOCKS      "true" | "false"   (default: "true" unless API_BASE_URL is set)
//   API_BASE_URL               API Gateway invoke URL
//   AWS_REGION                 e.g. eu-west-2
//   COGNITO_USER_POOL_ID       e.g. eu-west-2_AbCdEfGhI
//   COGNITO_CLIENT_ID          Cognito app client id (no secret)
//   STRIPE_PUBLISHABLE_KEY     pk_test_... or pk_live_...
//
// Never put secrets here. This file ships to every visitor's browser. (The Anthropic API key and Stripe secret key
// belong in the backend only.)
import { writeFile } from 'node:fs/promises';
import { fileURLToPath } from 'node:url';

const env = process.env;
const apiBase = env.API_BASE_URL ?? '';
const useMocks = (env.STUDENTSWAP_USE_MOCKS ?? (apiBase ? 'false' : 'true')) !== 'false';
const q = (v) => JSON.stringify(v ?? '');

const out = `// GENERATED by scripts/write-env.mjs. Edit the environment variables, not this file.
export const USE_MOCKS = ${useMocks};
export const API_BASE_URL = ${q(apiBase)};
export const AWS_REGION = ${q(env.AWS_REGION)};
export const COGNITO_USER_POOL_ID = ${q(env.COGNITO_USER_POOL_ID)};
export const COGNITO_CLIENT_ID = ${q(env.COGNITO_CLIENT_ID)};
export const STRIPE_PUBLISHABLE_KEY = ${q(env.STRIPE_PUBLISHABLE_KEY)};
`;

if (!useMocks) {
  const missing = ['API_BASE_URL', 'COGNITO_USER_POOL_ID', 'COGNITO_CLIENT_ID', 'STRIPE_PUBLISHABLE_KEY'].filter(
    (k) => !env[k],
  );
  if (missing.length) console.warn(`write-env: live mode but missing ${missing.join(', ')}`);
}
if (env.STRIPE_PUBLISHABLE_KEY?.startsWith('sk_'))
  throw new Error('write-env: that looks like a Stripe SECRET key. Use the publishable key (pk_...).');

// Default: dist/src/config/env.js (the build output). Pass a path to write elsewhere.
const target = process.argv[2] ?? fileURLToPath(new URL('../dist/src/config/env.js', import.meta.url));
await writeFile(target, out);
console.log(`write-env: wrote ${target} (USE_MOCKS=${useMocks})`);
